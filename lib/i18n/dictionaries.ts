const DICTS: Record<Locale, Dict> = { en, ko, ne }

export function isLocale(v: unknown): v is Locale {
  return typeof v === 'string' && (LOCALES as readonly string[]).includes(v)
}

export type TFn = (key: Key, params?: Record<string, string | number>) => string
export type LabelFn = (prefix: 'status' | 'type' | 'cat', value: string | null | undefined) => string

export function makeI18n(locale: Locale): { t: TFn; label: LabelFn; locale: Locale } {
  const dict = DICTS[locale] ?? en
  const t: TFn = (key, params) => {
    let s: string = dict[key] ?? en[key] ?? key
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
  const label: LabelFn = (prefix, value) => {
    if (!value) return ''
    const k = `${prefix}.${value}`
    const found = (dict as Record<string, string>)[k] ?? (en as Record<string, string>)[k]
    return found ?? value
  }
  return { t, label, locale }
}
